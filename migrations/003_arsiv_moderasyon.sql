create or replace function public.admin_nk_ders_birlestir(p_admin_token text,p_kaynak_id integer,p_hedef_id integer,
    p_neden text default 'tekrar',p_not text default null)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public
as $$
declare kaynak public.nk_dersler;hedef public.nk_dersler;tasinan integer;
begin
    if not public._admin_token_gecerli_mi(p_admin_token) then return jsonb_build_object('hata','yetkisiz'); end if;
    if p_kaynak_id=p_hedef_id or p_neden not in ('tekrar','yanlis_ders','diger') or char_length(coalesce(p_not,''))>1000
        then return jsonb_build_object('hata','gecersiz_birlestirme'); end if;
    perform pg_advisory_xact_lock(least(p_kaynak_id,p_hedef_id));
    perform pg_advisory_xact_lock(greatest(p_kaynak_id,p_hedef_id));
    select * into kaynak from public.nk_dersler where id=p_kaynak_id;
    select * into hedef from public.nk_dersler where id=p_hedef_id;
    if kaynak.id is null or hedef.id is null then return jsonb_build_object('hata','bulunamadi'); end if;
    if kaynak.bolum_id<>hedef.bolum_id then return jsonb_build_object('hata','farkli_bolum'); end if;
    update public.sorular set ders_id=p_hedef_id where ders_id=p_kaynak_id; get diagnostics tasinan=row_count;
    insert into public.nk_moderasyon_gecmisi(hedef_turu,hedef_id,islem,neden,aciklama,iliskili_hedef_id)
        values('ders',p_kaynak_id::text,'birlestirildi',p_neden,nullif(btrim(p_not),''),p_hedef_id::text);
    delete from public.nk_dersler where id=p_kaynak_id;
    return jsonb_build_object('basarili',true,'tasinan_soru',tasinan,'hedef_id',p_hedef_id);
end; $$;
