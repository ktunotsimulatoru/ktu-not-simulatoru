-- Fakülte/bölüm sayaçları tek sunucu sorgusunda hesaplanır; soru kimlikleri tarayıcıya taşınmaz.
create or replace function public.nk_klasor_sayaclari()
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public
as $$
declare u uuid := auth.uid(); sonuc jsonb;
begin
    if not public.nk_dogrulanmis_uye(u) then raise exception 'yetkisiz'; end if;
    select jsonb_build_object(
        'fakulteler', coalesce((select jsonb_agg(to_jsonb(x) order by x.id) from (
            select f.id, count(distinct d.id)::integer as ders_sayisi,
                   count(distinct s.id)::integer as soru_sayisi
            from public.fakulteler f left join public.bolumler b on b.fakulte_id=f.id
            left join public.nk_dersler d on d.bolum_id=b.id
            left join public.sorular s on s.ders_id=d.id and s.durum='onaylandi'
            group by f.id) x), '[]'::jsonb),
        'bolumler', coalesce((select jsonb_agg(to_jsonb(x) order by x.id) from (
            select b.id, count(distinct d.id)::integer as ders_sayisi,
                   count(distinct s.id)::integer as soru_sayisi
            from public.bolumler b left join public.nk_dersler d on d.bolum_id=b.id
            left join public.sorular s on s.ders_id=d.id and s.durum='onaylandi'
            group by b.id) x), '[]'::jsonb)
    ) into sonuc;
    return sonuc;
end; $$;
revoke all on function public.nk_klasor_sayaclari() from public, anon;
grant execute on function public.nk_klasor_sayaclari() to authenticated;

create or replace function public.nk_ders_ara(
    p_bolum_id integer, p_arama text default null, p_limit integer default 24, p_offset integer default 0,
    p_siralama text default 'ad')
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public
as $$
declare u uuid := auth.uid(); l integer := least(greatest(coalesce(p_limit,24),1),50);
    o integer := greatest(coalesce(p_offset,0),0); q text := lower(nullif(btrim(p_arama),'')); sonuc jsonb;
begin
    if not public.nk_dogrulanmis_uye(u) then raise exception 'yetkisiz'; end if;
    with eslesen as (
        select d.id,d.bolum_id,d.ders_adi,d.ders_kodu,d.ders_kodu_standart,
               count(s.id) filter (where s.durum='onaylandi')::integer as soru_sayisi
        from public.nk_dersler d left join public.sorular s on s.ders_id=d.id
        where d.bolum_id=p_bolum_id and (q is null or lower(d.ders_adi) like '%'||q||'%'
              or lower(coalesce(d.ders_kodu_standart,d.ders_kodu,'')) like '%'||q||'%')
        group by d.id
    ), sayfa as (
        select * from eslesen order by case when p_siralama='soru' then soru_sayisi end desc, ders_adi, id limit l offset o
    )
    select jsonb_build_object('toplam',(select count(*) from eslesen),
        'satirlar',coalesce((select jsonb_agg(to_jsonb(sayfa) order by ders_adi,id) from sayfa),'[]'::jsonb)) into sonuc;
    return sonuc;
end; $$;
revoke all on function public.nk_ders_ara(integer,text,integer,integer,text) from public, anon;
grant execute on function public.nk_ders_ara(integer,text,integer,integer,text) to authenticated;

create or replace function public.nk_icerik_bildir(p_soru_id uuid, p_neden text, p_aciklama text default null)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public
as $$
declare u uuid := auth.uid(); sahip uuid; yeni_id uuid;
begin
    if not public.nk_dogrulanmis_uye(u) then return jsonb_build_object('hata','yetkisiz'); end if;
    if p_neden not in ('okunmuyor','yanlis_ders','yanlis_bilgi','tekrar','telif','kisisel_veri','spam','diger')
       or char_length(coalesce(p_aciklama,''))>1000 then return jsonb_build_object('hata','gecersiz_bildirim'); end if;
    select kullanici_id into sahip from public.sorular where id=p_soru_id and durum='onaylandi';
    if not found then return jsonb_build_object('hata','bulunamadi'); end if;
    if sahip=u then return jsonb_build_object('hata','kendi_icerigin'); end if;
    if (select count(*) from public.nk_icerik_bildirimleri where bildiren_kullanici_id=u
        and olusturulma_tarihi>now()-interval '24 hours')>=10 then return jsonb_build_object('hata','sinir_asildi'); end if;
    begin
        insert into public.nk_icerik_bildirimleri(soru_id,bildiren_kullanici_id,neden,aciklama)
        values(p_soru_id,u,p_neden,nullif(btrim(p_aciklama),'')) returning id into yeni_id;
    exception when unique_violation then return jsonb_build_object('hata','zaten_bildirildi'); end;
    return jsonb_build_object('basarili',true,'id',yeni_id);
end; $$;
revoke all on function public.nk_icerik_bildir(uuid,text,text) from public, anon;
grant execute on function public.nk_icerik_bildir(uuid,text,text) to authenticated;

