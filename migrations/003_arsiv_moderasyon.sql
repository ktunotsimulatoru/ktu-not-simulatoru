create or replace function public.admin_soru_modere_et(p_admin_token text,p_id uuid,p_karar text,p_neden text,p_not text default null)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public
as $$
declare eski text;
begin
    if not public._admin_token_gecerli_mi(p_admin_token) then return jsonb_build_object('hata','yetkisiz'); end if;
    if p_karar not in ('onaylandi','reddedildi') or p_neden not in
       ('uygun','okunmuyor','yanlis_ders','yanlis_bilgi','tekrar','telif','kisisel_veri','spam','diger')
       or (p_karar='reddedildi' and p_neden='uygun') or char_length(coalesce(p_not,''))>1000 then
        return jsonb_build_object('hata','gecersiz_karar'); end if;
    select durum into eski from public.sorular where id=p_id for update;
    if not found then return jsonb_build_object('hata','bulunamadi'); end if;
    update public.sorular set durum=p_karar,moderasyon_nedeni=p_neden,
        moderasyon_notu=nullif(btrim(p_not),''),moderasyon_tarihi=now() where id=p_id;
    insert into public.nk_moderasyon_gecmisi(hedef_turu,hedef_id,islem,onceki_durum,yeni_durum,neden,aciklama)
        values('soru',p_id::text,p_karar,eski,p_karar,p_neden,nullif(btrim(p_not),''));
    if p_karar='reddedildi' then
        update public.nk_icerik_bildirimleri set durum='kapatildi',sonuclanma_tarihi=now(),sonuc_notu='İçerik reddedildi.'
        where soru_id=p_id and durum='acik';
    end if;
    return jsonb_build_object('basarili',true);
end; $$;
