    if not public._admin_token_gecerli_mi(p_admin_token) then raise exception 'yetkisiz'; end if;
    with eslesen as (
        select r.id,r.soru_id,r.neden,r.aciklama,r.durum,r.sonuc_notu,r.olusturulma_tarihi,r.sonuclanma_tarihi,
            u.email bildiren_email,s.durum soru_durumu,d.ders_adi,d.ders_kodu
        from public.nk_icerik_bildirimleri r join public.sorular s on s.id=r.soru_id
        join public.nk_dersler d on d.id=s.ders_id left join auth.users u on u.id=r.bildiren_kullanici_id
        where p_durum is null or p_durum='' or r.durum=p_durum
    ), sayfa as (select * from eslesen order by olusturulma_tarihi desc,id limit l offset o)
    select jsonb_build_object('toplam',(select count(*) from eslesen),
      'satirlar',coalesce((select jsonb_agg(to_jsonb(sayfa) order by olusturulma_tarihi desc,id) from sayfa),'[]'::jsonb)) into sonuc;
    return sonuc;
end; $$;
