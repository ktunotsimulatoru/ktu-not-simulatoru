create or replace function public.admin_nk_bildirim_kapat(p_admin_token text,p_id uuid,p_not text default null)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public
as $$
declare hedef uuid;
begin
    if not public._admin_token_gecerli_mi(p_admin_token) then return jsonb_build_object('hata','yetkisiz'); end if;
    if char_length(coalesce(p_not,''))>1000 then return jsonb_build_object('hata','gecersiz_not'); end if;
    update public.nk_icerik_bildirimleri set durum='kapatildi',sonuc_notu=nullif(btrim(p_not),''),sonuclanma_tarihi=now()
        where id=p_id and durum='acik' returning soru_id into hedef;
    if hedef is null then return jsonb_build_object('hata','bulunamadi'); end if;
    insert into public.nk_moderasyon_gecmisi(hedef_turu,hedef_id,islem,neden,aciklama,iliskili_hedef_id)
        values('bildirim',p_id::text,'bildirim_kapatildi','diger',nullif(btrim(p_not),''),hedef::text);
    return jsonb_build_object('basarili',true);
end; $$;
revoke all on function public.admin_nk_bildirim_kapat(text,uuid,text) from public;
grant execute on function public.admin_nk_bildirim_kapat(text,uuid,text) to anon, authenticated;

commit;

