        values('ders',p_id::text,'duzenlendi',concat_ws(' — ',eski.ders_kodu,eski.ders_adi),
            concat_ws(' — ',yeni.ders_kodu,yeni.ders_adi),'diger','Ders bilgileri güncellendi.');
    return json_build_object('basarili',true);
exception when check_violation then
    return json_build_object('hata','gecersiz_ders_kodu');
when unique_violation then
    return json_build_object('hata','tekrar_ders_kodu');
end; $$;
