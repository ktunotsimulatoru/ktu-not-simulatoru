create or replace function public.nk_ders_kodu_standartlastir(p_kod text)
returns text language sql immutable set search_path = pg_catalog
as $$
    select case
        when nullif(btrim(p_kod), '') is null then null
        when regexp_replace(upper(translate(btrim(p_kod), 'çğıöşüÇĞİÖŞÜ', 'cgiosuCGIOSU')), '[^A-Z0-9]', '', 'g')
             ~ '^[A-Z]{2,10}[0-9]{2,4}[A-Z]?$'
        then regexp_replace(upper(translate(btrim(p_kod), 'çğıöşüÇĞİÖŞÜ', 'cgiosuCGIOSU')), '[^A-Z0-9]', '', 'g')
        else null
    end;
$$;

alter table public.nk_dersler add column if not exists ders_kodu_standart text;
update public.nk_dersler
set ders_kodu_standart = public.nk_ders_kodu_standartlastir(ders_kodu),
    ders_kodu = public.nk_ders_kodu_standartlastir(ders_kodu)
where public.nk_ders_kodu_standartlastir(ders_kodu) is not null
  and (ders_kodu is distinct from public.nk_ders_kodu_standartlastir(ders_kodu)
       or ders_kodu_standart is distinct from public.nk_ders_kodu_standartlastir(ders_kodu));
update public.nk_dersler
set ders_kodu_standart = null
where public.nk_ders_kodu_standartlastir(ders_kodu) is null
  and ders_kodu_standart is not null;
create index if not exists nk_dersler_bolum_kod_idx on public.nk_dersler(bolum_id, ders_kodu_standart)
    where ders_kodu_standart is not null;

create or replace function public.nk_ders_kodu_yaz()
returns trigger language plpgsql set search_path = pg_catalog, public
as $$
declare v text;
begin
    if nullif(btrim(new.ders_kodu), '') is null then
        new.ders_kodu := null; new.ders_kodu_standart := null; return new;
    end if;
    v := public.nk_ders_kodu_standartlastir(new.ders_kodu);
    if v is null then
        raise exception 'Ders kodu 2-10 harf ve ardından 2-4 rakam biçiminde olmalı (ör. BLM301).'
            using errcode = '23514';
    end if;
    if not (tg_op='UPDATE' and old.bolum_id=new.bolum_id and old.ders_kodu_standart=v)
       and exists(select 1 from public.nk_dersler d
                  where d.bolum_id=new.bolum_id and d.ders_kodu_standart=v
                    and d.id is distinct from new.id) then
        raise exception 'Bu bölümde % kodlu bir ders zaten var.', v using errcode = '23505';
    end if;
    new.ders_kodu := v; new.ders_kodu_standart := v;
    return new;
end; $$;
drop trigger if exists nk_ders_kodu_yaz on public.nk_dersler;
create trigger nk_ders_kodu_yaz before insert or update of ders_kodu, bolum_id on public.nk_dersler
for each row execute function public.nk_ders_kodu_yaz();

